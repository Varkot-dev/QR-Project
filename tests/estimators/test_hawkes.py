"""Synthetic ground-truth tests for the Hawkes toolkit.

These tests ARE the deliverable for Phase-3 Task 1: the simulator, the
exponential-kernel MLE, and the model-free count-variance branching
estimator are only trustworthy insofar as they recover known parameters
on data generated by the simulator itself (and, for the trap test, on
data generated by a process that is deliberately NOT Hawkes).
"""
from __future__ import annotations

import numpy as np
import pytest

from microstructure.estimators.hawkes import (
    HawkesFit,
    _nelder_mead,
    branching_count_variance,
    fit_hawkes_exp,
    hawkes_loglik,
    simulate_hawkes_exp,
    simulate_seasonal_hawkes_exp,
)

# ---------------------------------------------------------------------------
# Group 0: Nelder-Mead sanity check on a known quadratic (test the optimizer
# itself before trusting it to fit anything statistical).
# ---------------------------------------------------------------------------


def test_nelder_mead_recovers_quadratic_minimum():
    # f(x, y) = (x - 3)^2 + (y + 2)^2 + 7, minimum at (3, -2), f_min = 7.
    def f(p: np.ndarray) -> float:
        return float((p[0] - 3.0) ** 2 + (p[1] + 2.0) ** 2 + 7.0)

    x0 = np.array([0.0, 0.0])
    best_x, best_f, converged = _nelder_mead(f, x0, max_iter=500)
    assert converged
    assert abs(best_x[0] - 3.0) < 1e-3
    assert abs(best_x[1] - (-2.0)) < 1e-3
    assert abs(best_f - 7.0) < 1e-5


def test_nelder_mead_handles_rosenbrock_like_valley():
    # A harder, curved-valley function: minimum at (1, 1), f_min = 0.
    def f(p: np.ndarray) -> float:
        x, y = p
        return float(100.0 * (y - x**2) ** 2 + (1.0 - x) ** 2)

    x0 = np.array([-1.0, 1.5])
    best_x, best_f, _converged = _nelder_mead(f, x0, max_iter=2000)
    assert best_f < 1e-3
    assert abs(best_x[0] - 1.0) < 0.05
    assert abs(best_x[1] - 1.0) < 0.05


# ---------------------------------------------------------------------------
# Group 0b: log-likelihood formula verified against numerical integration
# of the intensity on a tiny hand-checkable case.
# ---------------------------------------------------------------------------


def test_loglik_matches_numerical_intensity_integration():
    """Verify Σ log λ(t_i) − ∫λ(t)dt against brute-force numerical intensity.

    Uses 10 fixed event times (not simulated) so the check is independent
    of the simulator. Integrates λ(t) = mu + Σ alpha*beta*exp(-beta(t-t_i))
    with a fine trapezoid rule over [0, T] and compares to the closed-form
    recursion used in hawkes_loglik.
    """
    times = np.array([1.0, 1.3, 2.1, 2.15, 3.0, 4.4, 4.5, 4.55, 6.0, 8.0])
    t_end = 10.0
    mu, alpha, beta = 0.3, 0.5, 1.5

    ll_closed = hawkes_loglik(times, t_end, mu, alpha, beta)

    # Brute-force: Σ log λ(t_i^-) exactly (no integration needed for the
    # sum term — λ just before each event, using only prior events).
    log_sum = 0.0
    for i, ti in enumerate(times):
        prior = times[:i]
        excitation = np.sum(alpha * beta * np.exp(-beta * (ti - prior))) if i > 0 else 0.0
        log_sum += np.log(mu + excitation)

    # Numerically integrate the compensator ∫_0^T λ(t) dt via fine trapezoid.
    grid = np.linspace(0.0, t_end, 2_000_000)
    excitation_grid = np.zeros_like(grid)
    for ti in times:
        mask = grid > ti
        excitation_grid[mask] += alpha * beta * np.exp(-beta * (grid[mask] - ti))
    lam_grid = mu + excitation_grid
    compensator_numeric = np.trapezoid(lam_grid, grid)

    ll_numeric = log_sum - compensator_numeric

    assert abs(ll_closed - ll_numeric) < 1e-3, (ll_closed, ll_numeric)


# ---------------------------------------------------------------------------
# Group 0c: simulate_hawkes_exp must reject explosive/invalid parameters at
# entry rather than hang. alpha >= 1 makes the branching ratio >= 1, so the
# expected number of descendants per event is infinite/non-convergent and
# Ogata thinning's while loop (bounded by t_end but driven by ever-growing
# excitation) never reaches t_end in finite time/memory. Verified: alpha=1.5
# never terminates without this guard.
# ---------------------------------------------------------------------------


