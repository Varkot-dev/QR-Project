@pytest.mark.parametrize("seed", [7, 8, 9])
def test_count_variance_recovers_branching_ratio(seed):
    times = simulate_hawkes_exp(TRUE_MU, TRUE_ALPHA, TRUE_BETA, T_END, seed=seed)
    n_hat = branching_count_variance(times, window=500.0, t_end=T_END)
    assert abs(n_hat - TRUE_ALPHA) < 0.05, f"seed={seed} n_hat={n_hat}"


def test_count_variance_guards_too_few_windows():
    times = np.array([1.0, 2.0, 3.0])
    with pytest.raises(ValueError):
        branching_count_variance(times, window=1.0, t_end=3.0)


def test_count_variance_guards_zero_variance():
    # Perfectly regular spacing (one event every 1.0s) with window=10.0
    # puts exactly 10 events in every non-overlapping window -> var == 0.
    times = np.arange(0.0, 10_000.0, 1.0)
    with pytest.raises(ValueError):
        branching_count_variance(times, window=10.0, t_end=10_000.0)


# ---------------------------------------------------------------------------
# Group 3: near-critical regime (alpha=0.85) — wider tolerances, documented.
# ---------------------------------------------------------------------------

NEAR_CRITICAL_ALPHA = 0.85


def test_near_critical_mle_recovers_within_widened_tolerance():
    """Near n=1, mu/alpha become weakly identified locally (research/02 §4
    pitfall 5: 'near-unidentifiability at n≈1'); we widen tolerances vs the
    n=0.4 case rather than pretend the estimator is equally sharp everywhere.
    """
    times = simulate_hawkes_exp(TRUE_MU, NEAR_CRITICAL_ALPHA, TRUE_BETA, T_END, seed=11)
    fit_times = times[times <= FIT_SUBSAMPLE_T]
    fit = fit_hawkes_exp(fit_times, FIT_SUBSAMPLE_T)
    assert abs(fit.alpha - NEAR_CRITICAL_ALPHA) < 0.08, f"alpha={fit.alpha}"
    assert abs(fit.mu - TRUE_MU) < 0.15, f"mu={fit.mu}"

    n_hat = branching_count_variance(times, window=500.0, t_end=T_END)
    assert abs(n_hat - NEAR_CRITICAL_ALPHA) < 0.12, f"n_hat={n_hat}"


# ---------------------------------------------------------------------------
# Group 4: Poisson refutation test (the Filimonov-Sornette trap).
# ---------------------------------------------------------------------------


def test_poisson_refutation_both_estimators_report_near_zero():
    """A pure Poisson stream (alpha=0) must NOT look self-exciting.

    Note: we only assert on fit.alpha here, not fit.beta. When the true
    process has no self-excitation, beta (the kernel decay rate) is
    unidentified/degenerate at alpha=0 — there's no kernel timescale to
    recover, since the excitation term alpha*beta*R_i vanishes regardless
    of beta once alpha->0. The MLE surface is essentially flat in beta at
    that point, so a fitted beta value is not meaningful evidence of
    anything here and correctly is not asserted on.
    """
    rng = np.random.default_rng(21)
    rate = 1.0
    t_end = 200_000.0
    n_expected = int(rate * t_end * 1.05)
    gaps = rng.exponential(1.0 / rate, size=n_expected)
    times = np.cumsum(gaps)
    times = times[times <= t_end]

    fit_times = times[times <= FIT_SUBSAMPLE_T]
    fit = fit_hawkes_exp(fit_times, FIT_SUBSAMPLE_T)
    assert fit.alpha < 0.05, f"fitted alpha={fit.alpha} on pure Poisson"

    n_hat = branching_count_variance(times, window=500.0, t_end=t_end)
    assert n_hat < 0.05, f"count-variance n_hat={n_hat} on pure Poisson"


def test_regime_switching_poisson_produces_spurious_endogeneity_trap():
    """THE TRAP (Filimonov & Sornette 2015, research/02-hawkes-processes.md,
    'The calibration counterattack' section, §2.4-equivalent discussion):
    n̂ ≈ near-critical can be MANUFACTURED FROM NOTHING. Fitting a Hawkes
    model (or the count-variance estimator) to a regime-switching Poisson
    process — no self-excitation anywhere, only a rate that alternates
    between a low and a high value on a fixed clock — produces a SPURIOUS
    positive branching-ratio estimate, because clustering induced by rate
    non-stationarity is statistically indistinguishable, to both a
    likelihood fit and a count-mean/variance test, from clustering induced
    by genuine self-excitation.

    This is why deseasonalization (fitting or removing a time-varying
    baseline mu(t) BEFORE testing for endogeneity) is not optional: any
    Hawkes/branching-ratio estimate computed on a non-stationary-rate
    series conflates "the rate changes over time" with "events cause more
    events," and the two are observationally similar in aggregate count
    statistics. We assert n_hat > 0.2 for count-variance and fitted
    alpha > 0.5 for the MLE here specifically to document that the
    spurious effect is not a rounding error in either estimator — it is
    large enough, in both, to be mistaken for real, moderate-to-severe
    endogeneity.
    """
    rng = np.random.default_rng(22)
    low_rate, high_rate = 0.5, 2.0
    regime_len = 5000.0
    t_end = 200_000.0

    times: list[float] = []
    t = 0.0
    regime_start = 0.0
    is_low = True
    while regime_start < t_end:
        rate = low_rate if is_low else high_rate
        regime_end = min(regime_start + regime_len, t_end)
        t = regime_start
        while True:
            t += rng.exponential(1.0 / rate)
            if t >= regime_end:
                break
            times.append(t)
        regime_start = regime_end
        is_low = not is_low

    times_arr = np.asarray(times, dtype=np.float64)

    n_hat = branching_count_variance(times_arr, window=500.0, t_end=t_end)
    assert n_hat > 0.2, (
        f"expected the regime-switching trap to produce spurious n_hat > 0.2, "
        f"got {n_hat}"
    )

    fit_times = times_arr[times_arr <= FIT_SUBSAMPLE_T]
    fit = fit_hawkes_exp(fit_times, FIT_SUBSAMPLE_T)
    assert fit.alpha > 0.5, (
        f"expected the regime-switching trap to also fool the MLE with "
        f"fitted alpha > 0.5, got {fit.alpha}"
    )


# ---------------------------------------------------------------------------
# Group 5: simulate_seasonal_hawkes_exp (Phase-3 Task 2 rebuild) — a Hawkes
# process with a genuinely time-varying (periodic, piecewise-constant)
# baseline rate, for testing business-time rescaling against a real
# generative model rather than a post-hoc-thinned approximation.
# ---------------------------------------------------------------------------


def test_simulate_seasonal_rejects_invalid_parameters():
    flat_shape = np.ones(48)
    with pytest.raises(ValueError):
        simulate_seasonal_hawkes_exp(0.0, 0.4, 2.0, 1000.0, flat_shape, seed=1)
    with pytest.raises(ValueError):
        simulate_seasonal_hawkes_exp(-0.1, 0.4, 2.0, 1000.0, flat_shape, seed=1)
    with pytest.raises(ValueError):
        simulate_seasonal_hawkes_exp(0.5, -0.1, 2.0, 1000.0, flat_shape, seed=1)
    with pytest.raises(ValueError):
        simulate_seasonal_hawkes_exp(0.5, 1.0, 2.0, 1000.0, flat_shape, seed=1)
    with pytest.raises(ValueError):
        simulate_seasonal_hawkes_exp(0.5, 0.4, 0.0, 1000.0, flat_shape, seed=1)
    with pytest.raises(ValueError):
        simulate_seasonal_hawkes_exp(0.5, 0.4, 2.0, 0.0, flat_shape, seed=1)
    with pytest.raises(ValueError):
        simulate_seasonal_hawkes_exp(0.5, 0.4, 2.0, 1000.0, np.array([]), seed=1)
    with pytest.raises(ValueError):
        # non-positive entry in shape
        bad_shape = np.ones(48)
        bad_shape[3] = 0.0
        simulate_seasonal_hawkes_exp(0.5, 0.4, 2.0, 1000.0, bad_shape, seed=1)
    with pytest.raises(ValueError):
        # non-finite entry in shape
        bad_shape = np.ones(48)
        bad_shape[3] = np.nan
        simulate_seasonal_hawkes_exp(0.5, 0.4, 2.0, 1000.0, bad_shape, seed=1)


def test_simulate_seasonal_stationary_shape_recovers_known_parameters():
    """Sanity: a flat (mean-1) shape gives no seasonal confound, so a fit on
    the seasonal simulator's output should recover parameters just as well
    as the unseasonal simulator does (Group 1's tolerances)."""
    flat_shape = np.ones(48)
    times = simulate_seasonal_hawkes_exp(TRUE_MU, TRUE_ALPHA, TRUE_BETA, T_END, flat_shape, seed=7)
    fit_times = times[times <= FIT_SUBSAMPLE_T]
    fit = fit_hawkes_exp(fit_times, FIT_SUBSAMPLE_T)
    assert fit.converged
    assert abs(fit.alpha - TRUE_ALPHA) < 0.05, f"alpha={fit.alpha}"
    assert abs(fit.mu - TRUE_MU) < 0.08, f"mu={fit.mu}"


def test_simulate_seasonal_reduces_to_unseasonal_statistically():
    """With shape≡1, the seasonal simulator's output should be statistically
    indistinguishable (matched event count and fitted-parameter ballpark)
    from `simulate_hawkes_exp` on the same parameters -- not the same exact
    event times (the acceptance draws differ once lambda_bar's composition
    differs), but the same underlying distribution."""
    flat_shape = np.ones(48)
    seasonal_times = simulate_seasonal_hawkes_exp(
        TRUE_MU, TRUE_ALPHA, TRUE_BETA, T_END, flat_shape, seed=7
    )
    unseasonal_times = simulate_hawkes_exp(TRUE_MU, TRUE_ALPHA, TRUE_BETA, T_END, seed=7)

    # Event counts should be close (same Poisson-driven rate structure);
    # allow a generous relative tolerance since seeds drive different
    # candidate-acceptance sequences.
    rel_diff = abs(seasonal_times.size - unseasonal_times.size) / unseasonal_times.size
    assert rel_diff < 0.05, (
        f"seasonal n={seasonal_times.size} vs unseasonal n={unseasonal_times.size}, "
        f"rel_diff={rel_diff}"
    )

    fit_times = seasonal_times[seasonal_times <= FIT_SUBSAMPLE_T]
    fit = fit_hawkes_exp(fit_times, FIT_SUBSAMPLE_T)
    assert abs(fit.alpha - TRUE_ALPHA) < 0.05, f"alpha={fit.alpha}"
