    with pytest.raises(ValueError):
        simulate_hawkes_exp(0.5, 1.0, 2.0, 1000.0, seed=1)
    with pytest.raises(ValueError):
        simulate_hawkes_exp(0.5, 1.5, 2.0, 1000.0, seed=1)


